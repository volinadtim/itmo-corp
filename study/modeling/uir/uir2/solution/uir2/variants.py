@dataclass(frozen=True)
class SystemSpec:
    """Структура системы из таблицы 1."""

    devices: int
    buffers: tuple[int, ...]
    law: str | None  # "E2", "H1,5": закон в одном из приборов; None: все экспоненциальные


@dataclass(frozen=True)
class Variant:
    n1: int
    n2: int
    ng: int
    system1: SystemSpec
    system2: SystemSpec
    criterion: str  # буква а–д
    lam: float
    b: float
    probs: tuple[float, float, float]

    @property
    def code(self) -> str:
        return f"{self.n1}/{self.n2}/{self.ng}"

    def device_probs(self, devices: int) -> tuple[float, ...]:
        """Вероятности занятия приборов по указаниям к таблице 2."""
        p1, p2, p3 = self.probs
        if devices == 3:
            return (p1, p2, p3)
        if devices == 2:
            return (p1, p2 + p3)
        return (1.0,)


def _buffers(text: str, devices: int) -> tuple[int, ...]:
    parts = tuple(int(x) for x in text.split("/"))
    if len(parts) != devices:
        # Одно число: общий накопитель перед всеми приборами: другая модель.
        raise NotImplementedError(
            f"общий накопитель «{text}» для {devices} приборов не поддерживается"
        )
    return parts


def load(n1: int, n2: int, ng: int) -> Variant:
    k1, b1, _, _, _, crit1 = TABLE1[n1]
    _, _, k2, law2, b2, crit2 = TABLE1[n2]
    # Указание 3: при нечётной сумме N1+N2 критерий берётся по N1, при чётной: по N2.
    criterion = crit1 if (n1 + n2) % 2 else crit2
    lam, b, probs = TABLE2[ng]
    return Variant(
        n1=n1,
        n2=n2,
        ng=ng,
        system1=SystemSpec(k1, _buffers(b1, k1), None),
        system2=SystemSpec(k2, _buffers(b2, k2), law2),
        criterion=criterion,
        lam=lam,
        b=b,
        probs=probs,
    )


def law_phases(law: str) -> int:
    """Число фаз для закона из таблицы 1: "E2" → 2."""
    if law.startswith("E"):
        return int(law[1:])
    # Гиперэкспонента H_v требует ещё и выбора q: в этом расчёте не реализована.
    raise NotImplementedError(f"закон {law} не поддерживается, только Эрланг")


def special_device(spec: SystemSpec) -> int:
    """В какой прибор ставить неэкспоненциальный закон.

    Задание разрешает любой. Берётся прибор с самым большим накопителем:
    там закон обслуживания влияет на очередь, а значит, на критерий.
    """
    return max(range(spec.devices), key=lambda i: (spec.buffers[i], -i))
