def h(text, level=1):
    doc.add_heading(text, level=level)


def p(text, bold=False, italic=False, align=None, size=None):
    para = doc.add_paragraph()
    run = para.add_run(text)
    run.bold, run.italic = bold, italic
    if size:
        run.font.size = Pt(size)
    if align:
        para.alignment = align
    return para


def mono(text):
    para = doc.add_paragraph()
    run = para.add_run(text)
    run.font.name = "Courier New"
    run.font.size = Pt(10)
    return para


def table(rows, header=True, widths=None, size=10):
    t = doc.add_table(rows=len(rows), cols=len(rows[0]))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, row in enumerate(rows):
        for j, val in enumerate(row):
            cell = t.cell(i, j)
            cell.text = ""
            run = cell.paragraphs[0].add_run(str(val))
            run.font.size = Pt(size)
            run.bold = header and i == 0
            if widths:
                cell.width = Cm(widths[j])
    doc.add_paragraph()
    return t


def fig(path, caption):
    doc.add_picture(str(HERE / path), width=Cm(17))
    doc.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER
    p(caption, italic=True, align=WD_ALIGN_PARAGRAPH.CENTER, size=10)


def spectrum_block(name, sp, c_line, note=""):
    """Подробный расчёт частот для одного способа кодирования."""
    p(f"Расчёт для {name} (C = {mhz(c_line)} Мбит/с, t_b = 1/C = {mhz(1000 / c_line)} нс){note}:", bold=True)
    rows = [["Участок сигнала", "Частота", "f, МГц", "Кол-во участков", "Длительность, t_b"]]
    for row in sp["table"]:
        rows.append([describe(name, row), row["f_frac"], mhz(row["f"]), row["segments"], mhz(row["bits"])])
    table(rows, widths=[6.5, 2.2, 2, 2.6, 3])
    f_hi, f_lo = sp["f_hi"], sp["f_lo"]
    p(f"Верхняя граница fв = {mhz(f_hi)} МГц, нижняя fн = {mhz(f_lo)} МГц.")
    p(f"Спектр S = fв − fн = {mhz(f_hi)} − {mhz(f_lo)} = {mhz(sp['S'])} МГц.")
    terms = " + ".join(f"{mhz(r['f'])}·{mhz(r['bits'])}" for r in sp["table"])
    p(f"Средняя частота (взвешенная по длительности участков): fср = ({terms}) / {mhz(sp['total_bits'])} "
      f"= {mhz(sp['f_avg'])} МГц.")
    p(f"Необходимая полоса пропускания: F ≥ S = {mhz(sp['S'])} МГц (полоса {mhz(f_lo)}–{mhz(f_hi)} МГц, "
      f"основные гармоники). Для качественной передачи с 3-й гармоникой верхней частоты: "
      f"F = 3·fв − fн = {mhz(sp['F_q'])} МГц (полоса {mhz(f_lo)}–{mhz(3 * f_hi)} МГц).")


def describe(name, row):
    k = row["bits"] / max(row["segments"], 1)
    if name.startswith("RZ"):
        return "одинаковые биты подряд (период t_b)" if row["f_frac"] == "C" else "одиночный бит (период 2·t_b)"
    if "Манчестер" in name:
        return "полуинтервал t_b/2 (одинаковые биты)" if row["f_frac"] == "C" else "интервал t_b (смена бита)"
    if "MLT" in name:
        return f"уровень держится {mhz(k)} t_b (¼ периода)"
    return f"уровень держится {mhz(k)} t_b (½ периода)"


