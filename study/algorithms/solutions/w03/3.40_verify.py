"""
Проверка задачи 3.40:
какое минимальное число можно положить на нижний слой кучи из n=1000,
если добавить все натуральные числа 1..1000 ровно по одному разу?

Теория: лист на уровне 9 имеет 9 предков => нужны 9 различных значений < m,
т.е. m >= 10. Конструкция: по цепочке 1,2,...,10 от корня до листа,
остальные числа — бо'льшие в остальных ветвях. Здесь строим и проверяем.
"""


def valid_heap(arr):
    """Проверить свойство min-heap: предок <= потомок."""
    n = len(arr)
    for i in range(n):
        l, r = 2 * i + 1, 2 * i + 2
        if l < n and arr[i] > arr[l]:
            return False, (i, arr[i], l, arr[l])
        if r < n and arr[i] > arr[r]:
            return False, (i, arr[i], r, arr[r])
    return True, None


def build_min_heap_1000_with_chain(chain):
    """
    Строит массив-кучу размера 1000 (значения 1..1000, все различны),
    в которой цепочка chain (строго возрастающая) проходит по левой
    ветке от корня. Остальные значения размещаются так, чтобы
    min-heap свойство выполнялось.

    Конструкция:
    - ветка: индексы 0,1,3,7,15,...,511 (последовательность 2^{k+1}-1)
      для chain[0], chain[1], ...
    - все остальные вершины получают оставшиеся числа (большие), и мы
      должны расположить их так, чтобы свойство кучи соблюдалось.
    Делаем так: кладём в каждую непустую ветку по одному большому числу,
    а затем оставшиеся — заполняем построением кучи (sift_down) НО с
    сохранением цепочки: цепочка уже лежит на местах, sift_down на другие
    вершины не заденет вершины ветки, если они уже образуют кучу.
    """
    n = 1000
    chain = list(chain)

    # индексы левой ветки: 0,1,3,7,15,...
    branch = []
    x = 0
    while len(branch) < len(chain):
        branch.append(x)
        x = x * 2 + 1

    # заполняем массив: цепочка по ветке
    arr = [None] * n
    for idx, val in zip(branch, chain):
        arr[idx] = val

    # оставшиеся значения
    used = set(chain)
    rest = [v for v in range(1, n + 1) if v not in used]

    # Разложим rest по остальным слотам.
    # Стратегия: заполняем все None числами rest в любом порядке, а затем
    # восстанавливаем свойство кучи снизу вверх. Но sift_down/up могут
    # передвинуть числа ветки! Защитимся: пометим индексы ветки как
    # "занятые", и при обмене разрешим двигать только не-веточные вершины.
    # Проще: заполним слоты ветки значениями из rest СНИЗУ (большими),
    # а затем для всех остальных вершин сделаем heapify с ограничением.
    # Ещё проще — построим корректную кучу жадно:
    #   каждую не-веточную вершину заполним и применим sift_up, который
    #   обменивает только с предками. Если предок - вершина ветки с меньшим
    #   значением, обмен не произойдёт (т.к. у нас rest > chain по замыслу).
    arr_fill = [0] * n
    arr_fill[0] = 1
    # заранее проставим ветку
    for idx, val in zip(branch, chain):
        arr_fill[idx] = val

    rest_sorted = sorted(rest)  # малые -> большие, используем как есть

    # пройдём все вершины по возрастанию глубины: каждая получает
    # наименьшее доступное число, но НЕ меньше предка.
    # Реализуем простой корректный жадный алгоритм: fill в порядке индексов,
    # каждому None ставим число >= предка, не использованное.
    values_left = set(rest_sorted)
    for i in range(n):
        if arr_fill[i] != 0:
            continue
        # кандидаты: все >= предка
        parent = (i - 1) // 2 if i > 0 else None
        min_val = arr_fill[parent] if parent is not None else 1
        # выберем минимальное доступное число >= min_val
        cand = [v for v in values_left if v >= min_val]
        if not cand:
            raise RuntimeError("no candidate")
        chosen = min(cand)
        values_left.remove(chosen)
        arr_fill[i] = chosen

    return arr_fill


